#!/usr/bin/env python3
"""Assemble an Arch .pkg.tar.zst without makepkg/pacman (for non-Arch hosts).

Mirrors packaging/arch/PKGBUILD file layout. Uses GNU tar + zstd and a
generated .MTREE manifest. On Arch itself, prefer `makepkg -si`.
"""
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
def _version():
    import re

    text = open(os.path.join(ROOT, "pyproject.toml"), encoding="utf-8").read()
    return re.search(r'version\s*=\s*"([^"]+)"', text).group(1)


VERSION = _version()
PKGREL = "1"
PKGNAME = "athan-five-times"


def build_tree(dest):
    app = os.path.join(dest, "usr/share/athan-five-times")
    for sub in ("backend", "qml", "assets"):
        shutil.copytree(os.path.join(ROOT, sub), os.path.join(app, sub),
                        symlinks=True,
                        ignore=shutil.ignore_patterns("__pycache__"))
    for d, _, files in os.walk(app):
        for f in files:
            if f.endswith((".pyc", ".pyo")):
                os.remove(os.path.join(d, f))
    binpath = os.path.join(dest, "usr/bin/athan-five-times")
    os.makedirs(os.path.dirname(binpath), exist_ok=True)
    shutil.copy(os.path.join(ROOT, "packaging/common/athan-five-times"), binpath)
    os.chmod(binpath, 0o755)
    desk = os.path.join(dest, "usr/share/applications/com.azanprayer.app.desktop")
    os.makedirs(os.path.dirname(desk), exist_ok=True)
    shutil.copy(os.path.join(ROOT, "packaging/common/com.azanprayer.app.desktop"), desk)
    icondir = os.path.join(dest, "usr/share/icons/hicolor/scalable/apps")
    os.makedirs(icondir, exist_ok=True)
    shutil.copy(os.path.join(ROOT, "assets/kaaba.svg"),
                os.path.join(icondir, "com.azanprayer.app.svg"))
    licdir = os.path.join(dest, "usr/share/licenses", PKGNAME)
    os.makedirs(licdir, exist_ok=True)
    shutil.copy(os.path.join(ROOT, "LICENSE"), os.path.join(licdir, "LICENSE"))

    with open(os.path.join(dest, ".PKGINFO"), "w", encoding="utf-8") as f:
        f.write(
            "# Generated by packaging/arch/build-local.py (mirrors PKGBUILD)\n"
            f"pkgname = {PKGNAME}\n"
            f"pkgver = {VERSION}-{PKGREL}\n"
            "pkgdesc = Islamic prayer times with azan audio and adhkar (PySide6/Qt6)\n"
            "url = https://github.com/HtoZ27/Athan-Five-Times\n"
            "builddate = 0\npackager = H.Z.Tun\nsize = 0\narch = any\n"
            "license = GPL-3.0-or-later\n"
            "depend = python\ndepend = pyside6\ndepend = libnotify\n"
            "depend = hicolor-icon-theme\n"
        )

    entries = [".PKGINFO"]

    def walk_mtree(base):
        lines = ["/set type=file uid=0 gid=0 mode=0644"]
        lines.append(". type=dir uname=root gname=root mode=0755 time=0")
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames.sort()
            rel = os.path.relpath(dirpath, base)
            if rel != ".":
                lines.append(f"./{rel} type=dir uname=root gname=root "
                             f"mode=0755 time=0")
            for dn in list(dirnames):
                full = os.path.join(dirpath, dn)
                if os.path.islink(full):
                    relf = os.path.relpath(full, base)
                    lines.append(f"./{relf} type=link uname=root gname=root "
                                 f"mode=0777 time=0 link={os.readlink(full)}")
                    entries.append("./" + relf)
            for fn in sorted(filenames):
                if fn in (".PKGINFO", ".MTREE"):
                    continue
                full = os.path.join(dirpath, fn)
                relf = os.path.relpath(full, base)
                st = os.stat(full)
                if os.path.islink(full):
                    lines.append(f"./{relf} type=link uname=root gname=root "
                                 f"mode=0777 time=0 link={os.readlink(full)}")
                    continue
                h = hashlib.sha256()
                with open(full, "rb") as fh:
                    for chunk in iter(lambda: fh.read(65536), b""):
                        h.update(chunk)
                mode = "0755" if os.access(full, os.X_OK) else "0644"
                lines.append(
                    f"./{relf} type=file uname=root gname=root mode={mode} "
                    f"time=0 size={st.st_size} sha256digest={h.hexdigest()}")
                entries.append("./" + relf)
        return lines

    with open(os.path.join(dest, ".MTREE"), "w", encoding="utf-8") as f:
        f.write("\n".join(walk_mtree(dest)) + "\n")
    entries.insert(1, ".MTREE")
    return entries


def main():
    work = tempfile.mkdtemp(prefix="archpkg-")
    try:
        dest = os.path.join(work, "pkg")
        os.makedirs(dest)
        entries = build_tree(dest)
        out = os.path.join(
            ROOT, f"{PKGNAME}-{VERSION}-{PKGREL}-any.pkg.tar.zst")
        if os.path.exists(out):
            os.remove(out)
        subprocess.run(
            ["tar", "--sort=name", "--owner=0", "--group=0",
             "--mtime=@0", "-I", "zstd -19 -T0", "-cf", out,
             "-C", dest] + entries,
            check=True)
        print(f"Built: {out} ({os.path.getsize(out)} bytes)")
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
